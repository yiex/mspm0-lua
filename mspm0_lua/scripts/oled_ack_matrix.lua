-- Compare empty / short / long writes and oled.open on PA15/16
print("ACK_MATRIX")
i2c.open(1, "PA15", "PA16", 100000)
print("empty", i2c.write(1, 0x3c, bytes()) and 1 or 0)
print("cmd1", i2c.write(1, 0x3c, bytes(0x00)) and 1 or 0)
print("ae", i2c.write(1, 0x3c, bytes(0x00, 0xae)) and 1 or 0)
print("writev", i2c.writev(1, 0x3c, 0x00, 0xae) and 1 or 0)
print("af", i2c.write(1, 0x3c, bytes(0x00, 0xaf)) and 1 or 0)
i2c.close(1)
local ok, err = pcall(function()
  oled.open("PA15", "PA16")
  oled.fill(0xff)
  delay_ms(200)
  oled.clear()
  oled.cursor(0, 0)
  oled.print("OLED OK")
  oled.num(0, 2, 1234, 0)
end)
print(ok and "OLED_OK" or ("OLED_FAIL " .. tostring(err)))
