local address = 0x3c
local hz = 100000

local function write(payload)
  assert(i2c.write(address, payload, hz), "OLED I2C write failed")
end

-- SSD1306 128x64, page addressing mode.
write("\x00\xae\xd5\x80\xa8\x3f\xd3\x00\x40\x8d\x14\x20\x02\xa1\xc8\xda\x12\x81\xcf\xd9\xf1\xdb\x40\xa4\xa6\xaf")

local z8 = "\x00\x00\x00\x00\x00\x00\x00\x00"
local z7 = "\x00\x00\x00\x00\x00\x00\x00"
local blank = "\x40" .. z8 .. z8 .. z8 .. z8 .. z8 .. z8 .. z8 .. z7
local pages = {
  "\x00\xb0\x00\x10", "\x00\xb1\x00\x10",
  "\x00\xb2\x00\x10", "\x00\xb3\x00\x10",
  "\x00\xb4\x00\x10", "\x00\xb5\x00\x10",
  "\x00\xb6\x00\x10", "\x00\xb7\x00\x10",
}
for page = 1, 8 do
  write(pages[page])
  write(blank)
  write(blank)
  write("\x40\x00\x00")
end

-- Page 0, column 0. Six columns per digit, one blank column included.
write("\x00\xb0\x00\x10")
write("\x40\x00\x42\x7f\x40\x00\x00\x62\x51\x49\x49\x46\x00\x22\x49\x49\x49\x36\x00")

print("OLED_123_OK")
